export type ControlLabelMessageId = keyof typeof englishControlLabels;
export type ControlLabelParameters = Readonly<Record<string, string | number>>;
export type ControlLabelCatalogue = Readonly<Partial<Record<ControlLabelMessageId, string>>>;
export type ControlLabelTranslator = (
  message: ControlLabelMessageId,
  parameters?: ControlLabelParameters,
) => string;

/** Override translated IDs; missing messages keep their English fallback. */
export function createControlLabelTranslator(
  catalogue: ControlLabelCatalogue = {},
): ControlLabelTranslator {
  return (message, parameters = {}) => {
    const template = catalogue[message] ?? englishControlLabels[message];
    return template.replace(/\{([a-zA-Z]+)\}/g, (placeholder: string, name: string) =>
      parameters[name] === undefined ? placeholder : String(parameters[name]),
    );
  };
}

export function isControlLabelMessageId(value: string): value is ControlLabelMessageId {
  return Object.hasOwn(englishControlLabels, value);
}
